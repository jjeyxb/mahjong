def act_conf_for(class_name, seat=None, override=None):
    """這個 (類別, 座位) 要算成真事件,信心度至少要多少。

    override 不是 None 就一律用它(門檻掃描 / --act-conf 做對照實驗用)。
    """
    if override is not None:
        return override
    if (class_name, seat) in ACT_CONF_BY_CLASS_SEAT:
        return ACT_CONF_BY_CLASS_SEAT[(class_name, seat)]
    return ACT_CONF.get(class_name, 0.70)


def min_frames_for(class_name):
    """這個類別要成立,同一段裡至少要有幾幀落在該家框內。"""
    return MIN_FRAMES.get(class_name, DEFAULT_MIN_FRAMES)


def _contains(box, cx, cy):
    x, y, w, h = box
    return x <= cx <= x + w and y <= cy <= y + h


def classify(cx, cy, class_name):
    """判斷這個偵測框的中心點屬於誰。

    回傳 (verdict, shape):
        ("IGNORE", why)       落在排除區,不是真的事件
        ("P0".."P3", shape)   對應到某一家
        ("UNKNOWN", shape)    這個形狀的表沒涵蓋到這個位置——不要猜
        ("UNKNOWN", None)     這個類別沒有對應的形狀(例如流局)
    """
    for zone in IGNORE_ZONES:
        if _contains(zone["box"], cx, cy):
            return "IGNORE", zone["why"]

    shape = SHAPE_OF_CLASS.get(class_name)
    if shape is None:
        return "UNKNOWN", None

    for seat, entry in ZONES.get(ZONE_GROUP[shape], {}).items():
        if _contains(entry["box"], cx, cy):
            return seat, shape

    return "UNKNOWN", shape


def seat_status(shape, seat):
    """回傳這個 (形狀, 座位) 的狀態:confirmed / verified / inferred / missing。"""
    entry = ZONES.get(ZONE_GROUP.get(shape, shape), {}).get(seat)
    return entry["status"] if entry else "missing"


def iter_zones():
    """走訪所有已建表的區域,產生 (zone_group, seat, entry)。畫圖用。"""
    for group, seats in ZONES.items():
        for seat, entry in seats.items():
            yield group, seat, entry


def status_report():
    """回傳可以直接印出來的確認狀態表(每個元素一行)。"""
    lines = ["座標確認狀態(shape × seat):",
             "  ✓ 已確認 = 實機截圖,人親眼核對過",
             "  ✓ 已驗證 = 通過自動交叉驗證(指示燈/麻將規則一致性)",
             "  ? 推測   = 只有幾何推斷,沒有任何驗證",
             ""]
    for group in ("call", "win"):
        seats = ZONES.get(group, {})
        label = {"call": "吃/碰/槓+立直", "win": "和+自摸"}[group]
        if not seats:
            lines.append(f"  {label:<16} 完全沒有樣本")
            continue
        for seat in ("P0", "P1", "P2", "P3"):
            entry = seats.get(seat)
            if not entry:
                lines.append(f"  {label:<16} {seat}  沒有樣本")
                continue
            mark = {"confirmed": "✓ 已確認", "verified": "✓ 已驗證"}.get(
                entry["status"], "? 推測")
            lines.append(f"  {label:<14} {seat}  {mark}  {entry['note']}")
        lines.append("")
    return lines
