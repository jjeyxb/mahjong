"""用「宣告圖示出現在畫面哪個位置」判斷事件是哪一家發起的。

橫幅依字數分成幾種形狀,框大小不一樣,但位置不一定不一樣:

    call   吃 / 碰 / 槓      一個字,框約 169x159
    reach  立直             兩個字,框較寬扁(228x126)
    hora   和               一個字,框約 276x256
    tsumo  自摸             兩個字,框約 410x232

框大小四種都不同,但「位置」只有兩組——同一組裡的錨點幾乎重疊,只是字數
不同讓框往外長:

    call + reach   立直的中心點固定在 call 下方 11~18px(四家一致)
    hora + tsumo   自摸的中心點固定在和的右邊 3~8px(四家一致)

所以位置表只建兩組。實測 500 列資料,兩組的偏移量在四家身上都高度一致,
不是巧合。

流局不列入:那是整局的事件,不是某一家發起的,行動者不該因此改變。

=== 區域為什麼是「帶狀」而不是一個點 ===
宣告橫幅是從外側縮放淡入、滑到定位的,模型常常在動畫還沒播完就抓到了。
實測同一局 P2 碰三次,兩次抓到定位點 y≈325,一次抓到動畫中途的 y=197。
與其等動畫停下來再讀(白白犧牲幾十毫秒反應時間),不如把整條動畫路徑劃
進來——動畫中途抓到反而更早送出事件。這樣做的前提是四家的路徑彼此不
重疊,實測確實如此:橫幅沿著「從自己往桌子中心」的方向滑進來,四個方向
各不相同。

=== status 欄位的意思(很重要,不要混淆)===
    confirmed  座位歸屬有地面實況佐證(實機截圖,人親眼確認過是哪一家)
    verified   通過自動交叉驗證。兩種驗證方式:
                 call 組 —— 鳴牌之後指示燈應該移到鳴牌那家(run_step3)
                 win  組 —— 自摸者「必須」是當下行動者、榮和者「必須不是」,
                            這是麻將規則決定的,不符合就是座位判錯了
    inferred   位置是真實觀測到的,但「這個位置屬於哪一家」只是從幾何關係
               推出來的,沒有任何驗證。推錯的話事件會安靜地指派給錯的
               玩家,所以在被驗證之前都要當成可疑的。
    (沒有條目) 連樣本都還沒有。

為什麼要用查表而不是象限判斷:象限判斷一定會把每個偵測框指派給某一家,
沒辦法回答「這四家都不是」。查表可以——落在所有區域之外就回報 UNKNOWN。
事件誤判一次,mjai 事件流就整串錯掉,所以「不知道」比「猜錯」有價值。

=== 這張表是事件「發起者是誰」的唯一來源 ===
所有非摸打事件(吃/碰/槓/立直/和/自摸)的座位,一律以這張表判定,不從
指示燈推。理由:

  指示燈是間接證據——燈 -> 當下行動者 -> 假設事件發起者就是他,中間任何
  一環出錯都會往下傳遞;而且它會被角色立繪、鳴牌動畫遮擋,實測本來就有
  讀不出來的情況。座標是直接證據,模型看到宣告橫幅出現在哪裡,那就是誰。

  曾經考慮過的捷徑:自摸/立直的發起者「本來就是當下行動者」,所以可以不
  建表、直接沿用 TurnTracker。這是錯的方向——它把剛拔掉的指示燈相依性又
  插回來,而且只在指示燈全程正確時才成立。

指示燈只負責一件事:沒有任何事件、單純輪到下一家摸打時的換家判斷。那種
情況畫面上沒有任何宣告橫幅,除了燈之外沒有別的訊號可用。

代價要講清楚:這代表四家 × 每一種形狀都必須建表建對,漏一格那種事件就
永遠是 UNKNOWN。收集的工作量比走捷徑大,換來的是不依賴間接證據。
"""

